"""Converts the material-expressive-design skill's generated Palettes.kt into lib/ui/theme/palettes.dart.

Usage: python3 tool/gen_palettes_dart.py ~/.claude/skills/material-expressive-design/templates/ui/theme/Palettes.kt
"""
import re, sys

src = open(sys.argv[1]).read()
# Compose names that do not exist (or are deprecated) on Flutter's ColorScheme.
SKIP = {"background", "onBackground", "surfaceVariant"}
RENAME = {"inverseOnSurface": "onInverseSurface"}

entries = re.findall(r'(\w+)\(\s*"([^"]+)",\s*lightColorScheme\((.*?)\),\s*darkColorScheme\((.*?)\),\s*\)', src, re.S)
assert entries, "no palettes parsed"

def scheme(body, brightness):
    out = [f"      brightness: Brightness.{brightness},"]
    for name, hexv in re.findall(r'(\w+)\s*=\s*Color\((0x[0-9A-Fa-f]{8})\)', body):
        if name in SKIP:
            continue
        out.append(f"      {RENAME.get(name, name)}: Color({hexv}),")
    return "ColorScheme(\n" + "\n".join(out) + "\n    )"

lines = [
    "// GENERATED by tool/gen_palettes_dart.py from the material-expressive-design skill's",
    "// Palettes.kt. Do not hand-edit; regenerate instead.",
    "import 'package:flutter/material.dart';",
    "",
    "enum Palette {",
]
for i, (key, label, light, dark) in enumerate(entries):
    sep = ";" if i == len(entries) - 1 else ","
    lines.append(f"  {key.lower()}(\n    '{label}',\n    {scheme(light, 'light')},\n    {scheme(dark, 'dark')},\n  ){sep}")
lines += [
    "",
    "  const Palette(this.displayName, this.light, this.dark);",
    "",
    "  final String displayName;",
    "  final ColorScheme light;",
    "  final ColorScheme dark;",
    "",
    "  ColorScheme scheme(bool dark) => dark ? this.dark : light;",
    "}",
    "",
]
open("lib/ui/theme/palettes.dart", "w").write("\n".join(lines))
print(len(entries), "palettes")
